"""
Реалізація двох атак, які використовуються і на тренуванні (train.py),
і на оцінці (evaluate.py):

  1. FGSM (Fast Gradient Sign Method) — adversarial атака
  2. Gaussian Noise — шумова атака зі списку варіантів лабораторної

Обидві функції працюють з тензорами зображень у діапазоні [0, 1]
(звичайні пікселі, БЕЗ ImageNet mean/std нормалізації — та нормалізація
"захована" всередині самої моделі, першим шаром, див. model.py).
Завдяки цьому значення eps і sigma мають прямий, зрозумілий фізичний сенс
у термінах яскравості пікселя, а не в "перенормованому" просторі ознак.
"""
import torch
import torch.nn.functional as F


def fgsm_attack(model, x, y, eps, criterion=None):
    """Fast Gradient Sign Method (Goodfellow et al., 2015).

    Ідея: зробити ОДИН крок градієнтного підйому по loss функції відносно
    входу x (а не відносно ваг моделі, як при звичайному тренуванні),
    тобто змінити зображення в напрямку, який НАЙБІЛЬШЕ збільшує помилку
    моделі, обмежившись максимальною амплітудою збурення eps на кожен піксель:

        x_adv = clip(x + eps * sign(∇x CE(model(x), y)),  0, 1)

    Параметри:
      model  — атакована модель (forward має бути диференційовним відносно x)
      x      — батч зображень, значення в [0, 1], shape (N, 3, H, W)
      y      — справжні мітки класів (не adversarial target — це untargeted
               атака: мета просто "зламати" правильну відповідь, а не
               змусити модель передбачити конкретний "чужий" клас)
      eps    — розмір кроку атаки в одиницях [0,1] (L_inf-обмеження);
               eps=0 означає "без атаки" (повертає x без змін)
      criterion — функція втрат, за замовчуванням крос-ентропія

    sign(grad) навмисно використовується замість самого grad: величина
    градієнта в різних пікселях може дуже відрізнятись, а FGSM хоче
    рівномірно "зіпсувати" ВСІ пікселі на максимально дозволену величину eps
    у напрямку, що збільшує loss — тому береться лише ЗНАК градієнта.
    """
    if eps == 0:
        return x.clone()
    criterion = criterion or F.cross_entropy

    # requires_grad_(True): потрібно порахувати d(loss)/d(x), а не d(loss)/d(ваги)
    x_adv = x.clone().detach().requires_grad_(True)
    logits = model(x_adv)
    loss = criterion(logits, y)
    grad = torch.autograd.grad(loss, x_adv)[0]

    # Крок у напрямку ЗРОСТАННЯ loss (тому +, а не -, як при звичайному
    # градієнтному спуску по вагах) — модель повинна помилятись сильніше.
    x_adv = x_adv.detach() + eps * grad.sign()
    # clip назад у валідний діапазон пікселів [0,1] (інакше зображення
    # технічно вийде за межі того, що взагалі можна "показати"/зберегти).
    x_adv = torch.clamp(x_adv, 0.0, 1.0)
    return x_adv.detach()


def gaussian_noise_attack(x, sigma_low=0.01, sigma_high=0.08, p=0.5, generator=None):
    """Gaussian Noise атака (обраний варіант зі списку шумових атак лабораторної).

    Параметри задачі: mu=0, sigma ~ U(0.01, 0.08), p=0.5.

    Для кожного зображення в батчі:
      - з ймовірністю p до нього додається адитивний гаусів шум
        N(0, sigma^2), де sigma окремо (випадково) обирається для кожного
        зображення з рівномірного розподілу U(sigma_low, sigma_high);
      - з ймовірністю (1-p) зображення лишається без змін.

    Це НЕ adversarial атака (шум не залежить від градієнта моделі й не
    "цілиться" в її слабкі місця) — це стохастичне спотворення, що імітує
    реальний шум сенсора/каналу передачі, тому й trainable-параметрів чи
    доступу до model тут не потрібно (на відміну від fgsm_attack).
    """
    x_out = x.clone()
    n = x.shape[0]
    device = x.device

    # Для кожного зображення в батчі окремо вирішуємо, застосовувати шум чи ні.
    apply_mask = torch.rand(n, device=device, generator=None) < p
    if apply_mask.any():
        # Кожне зображення отримує СВОЄ випадкове sigma з діапазону
        sigmas = torch.empty(n, device=device).uniform_(sigma_low, sigma_high)
        noise = torch.randn_like(x)  # N(0, 1) шум тієї ж форми, що й x
        sigmas = sigmas.view(-1, 1, 1, 1)  # broadcast sigma на всі пікселі/канали
        noisy = x + noise * sigmas
        x_out[apply_mask] = noisy[apply_mask]

    return torch.clamp(x_out, 0.0, 1.0)
